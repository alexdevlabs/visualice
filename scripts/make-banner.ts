/**
 * The README banner, light and dark: `npx tsx scripts/make-banner.ts`.
 *
 * Writes assets/banner/banner-{light,dark}.svg (the source) and renders each to a 2x
 * PNG with Playwright, with Figtree loaded so the text matches the viewer. GitHub
 * shows the PNGs: an SVG in a README can't load web fonts.
 */
import path from "node:path";
import { promises as fs } from "node:fs";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "assets", "banner");

const W = 1280;
const H = 400;
const FONT = "Figtree, -apple-system, 'Segoe UI', 'Helvetica Neue', Arial, sans-serif";

interface Theme {
  bg: [string, string];
  ink: string;
  dim: string;
  tile: string;
  tileLine: string;
  tileText: string;
  iconRing: string;
}

const ACCENT = "#e8492a";

const THEMES: Record<"light" | "dark", Theme> = {
  light: {
    bg: ["#fbfaf6", "#f0ece3"],
    ink: "#16161a",
    dim: "#5d5a54",
    tile: "#ffffff",
    tileLine: "rgba(22,22,26,0.13)",
    tileText: "rgba(22,22,26,0.10)",
    iconRing: "rgba(22,22,26,0)",
  },
  dark: {
    bg: ["#1d1d22", "#121215"],
    ink: "#f4f2ec",
    dim: "#a9a59c",
    tile: "rgba(244,242,236,0.05)",
    tileLine: "rgba(244,242,236,0.16)",
    tileText: "rgba(244,242,236,0.10)",
    iconRing: "rgba(244,242,236,0.18)",
  },
};

const CHIPS = ["Every page", "Every UI state", "Every device"];

/** The app icon (assets/logo/visualice-app-icon.svg), placed at x,y and size px. */
function icon(x: number, y: number, size: number, t: Theme): string {
  const s = size / 1024;
  return `<g filter="url(#shadow)"><rect x="${x}" y="${y}" width="${size}" height="${size}" rx="${230 * s}" fill="#16161a" stroke="${t.iconRing}" stroke-width="1.5"/></g>
  <g transform="translate(${x} ${y}) scale(${s})"><g transform="translate(160 150) scale(11)">
    <path stroke="#f4f2ec" stroke-width="5.5" stroke-linecap="round" fill="none" d="M21 32 L13 27 M17 42 L9 42 M21 52 L13 57 M43 32 L51 27 M47 42 L55 42 M43 52 L51 57"/>
    <path stroke="#f4f2ec" stroke-width="3.5" stroke-linecap="round" fill="none" d="M27.5 14 L23.5 8 M36.5 14 L40.5 8"/>
    <circle cx="32" cy="42" r="17" fill="#f4f2ec"/><circle cx="32" cy="20" r="8.5" fill="${ACCENT}"/>
  </g></g>`;
}

/** One screenshot tile: a frame, a header bar and a few lines of "content". */
function tile(x: number, y: number, w: number, h: number, t: Theme, selected = false): string {
  const pad = Math.max(5, w * 0.08);
  const lines = [0.42, 0.56, 0.68]
    .map((f, i) => {
      const lw = (w - pad * 2) * [0.8, 0.6, 0.7][i];
      return `<rect x="${x + pad}" y="${y + h * f}" width="${lw}" height="${Math.max(3, h * 0.045)}" rx="2" fill="${t.tileText}"/>`;
    })
    .join("");
  const frame = selected
    ? `<rect x="${x - 4}" y="${y - 4}" width="${w + 8}" height="${h + 8}" rx="9" fill="none" stroke="${ACCENT}" stroke-width="2.5"/>`
    : "";
  return `${frame}<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="6" fill="${t.tile}" stroke="${t.tileLine}" stroke-width="1.5"/>
  <rect x="${x + pad}" y="${y + pad}" width="${w - pad * 2}" height="${h * 0.14}" rx="3" fill="${t.tileText}"/>${lines}`;
}

/** The right-hand motif: the viewer's canvas, a row per state, a column per device. */
function canvas(t: Theme): string {
  const devices = [
    { w: 156, h: 98 },
    { w: 74, h: 98 },
    { w: 46, h: 98 },
  ];
  const rows = [-42, 78, 198, 318];
  let out = "";
  rows.forEach((y, r) => {
    let x = 1006 + (r % 2) * 14;
    devices.forEach((d, c) => {
      out += tile(x, y, d.w, d.h, t, r === 1 && c === 0);
      x += d.w + 22;
    });
  });
  // Fade the motif into the background on its left edge.
  return `<g opacity="0.9" mask="url(#fade)">${out}</g>`;
}

function chips(x: number, y: number, t: Theme): string {
  let out = "";
  for (const label of CHIPS) {
    const w = 46 + label.length * 8.6;
    out += `<rect x="${x}" y="${y}" width="${w}" height="40" rx="20" fill="${ACCENT}" fill-opacity="0.08" stroke="${ACCENT}" stroke-opacity="0.38"/>
    <circle cx="${x + 20}" cy="${y + 20}" r="4.5" fill="${ACCENT}"/>
    <text x="${x + 33}" y="${y + 26}" font-family="${FONT}" font-size="17" font-weight="500" fill="${t.ink}">${label}</text>`;
    x += w + 12;
  }
  return out;
}

function banner(name: "light" | "dark"): string {
  const t = THEMES[name];
  return `<!-- README banner (${name}). Generated by scripts/make-banner.ts; exported to banner-${name}.png at 2x. -->
<svg width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" xmlns="http://www.w3.org/2000/svg" role="img" aria-label="visualice: every page and UI state of your site, on every device">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${t.bg[0]}"/><stop offset="1" stop-color="${t.bg[1]}"/></linearGradient>
    <linearGradient id="fadeGrad" x1="0" y1="0" x2="1" y2="0"><stop offset="0.77" stop-color="#fff" stop-opacity="0"/><stop offset="0.9" stop-color="#fff" stop-opacity="1"/></linearGradient>
    <mask id="fade"><rect width="${W}" height="${H}" fill="url(#fadeGrad)"/></mask>
    <clipPath id="card"><rect width="${W}" height="${H}" rx="22"/></clipPath>
    <filter id="shadow" x="-30%" y="-30%" width="160%" height="160%"><feDropShadow dx="0" dy="7" stdDeviation="9" flood-color="#000" flood-opacity="${name === "dark" ? 0.5 : 0.22}"/></filter>
  </defs>
  <g clip-path="url(#card)">
    <rect width="${W}" height="${H}" fill="url(#bg)"/>
    ${canvas(t)}
  </g>
  ${icon(112, 112, 176, t)}
  <text x="338" y="200" font-family="${FONT}" font-size="76" font-weight="700" letter-spacing="-1.5" fill="${t.ink}">visua<tspan fill="${ACCENT}">lice</tspan></text>
  <text x="341" y="246" font-family="${FONT}" font-size="26" fill="${t.dim}">Every page and UI state of your site, on every device.</text>
  ${chips(341, 278, t)}
</svg>
`;
}

async function fontFaces(): Promise<string> {
  const faces = await Promise.all(
    [400, 500, 700].map(async (weight) => {
      const file = path.join(
        root,
        `node_modules/@fontsource/figtree/files/figtree-latin-${weight}-normal.woff2`,
      );
      const data = (await fs.readFile(file)).toString("base64");
      return `@font-face{font-family:Figtree;font-weight:${weight};src:url(data:font/woff2;base64,${data}) format("woff2")}`;
    }),
  );
  return faces.join("\n");
}

await fs.mkdir(outDir, { recursive: true });
const css = await fontFaces();
const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: W, height: H }, deviceScaleFactor: 2 });
  for (const name of ["light", "dark"] as const) {
    const svg = banner(name);
    await fs.writeFile(path.join(outDir, `banner-${name}.svg`), svg);
    await page.setContent(
      `<!doctype html><html><head><style>${css}html,body{margin:0;background:transparent}svg{display:block}</style></head><body>${svg}</body></html>`,
    );
    await page.evaluate(() => document.fonts.ready);
    const png = path.join(outDir, `banner-${name}.png`);
    await page.locator("svg").screenshot({ path: png, omitBackground: true });
    console.log(`wrote ${path.relative(root, png)}`);
  }
} finally {
  await browser.close();
}
